package Level1ClassesAndObjectsBasics;

public class Hero {
    String heroName;
    int heroHP;
    int heroAttackPower;
    int heroDefense;
    int heroLevel;

    Hero(String heroName, int heroHP, int heroAttackPower, int heroDefense, int heroLevel) {
        this.heroName = heroName;
        this.heroHP = heroHP;
        this.heroAttackPower = heroAttackPower;
        this.heroDefense = heroDefense;
        this.heroLevel = heroLevel;
    }


}
